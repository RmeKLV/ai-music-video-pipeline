"""Find sudden vocal volume dips inside sung phrases: short-term level (20 ms) drops >= DROP dB below the
surrounding 400 ms level and recovers within 600 ms, while still inside a phrase.
Compares the vocal stem with the original mix in the same window: if the mix's 300-3000 Hz band dips too,
the dip was generated by ACE; if only the stem dips, the separator ducked the vocal.
usage: find_dips.py vocals.flac mix.wav [DROP_dB]"""
import sys, numpy as np, soundfile as sf
from scipy.ndimage import maximum_filter1d, median_filter
from scipy.signal import butter, sosfiltfilt

v, sr = sf.read(sys.argv[1], always_2d=True); m, msr = sf.read(sys.argv[2], always_2d=True)
DROP = float(sys.argv[3]) if len(sys.argv) > 3 else 8.0
assert sr == msr
n = min(len(v), len(m)); v = v[:n].mean(1); m = m[:n].mean(1)
mb = sosfiltfilt(butter(4, [300, 3000], "bp", fs=sr, output="sos"), m)
hop = int(0.02 * sr)
lev = lambda x: 20 * np.log10(np.sqrt(np.mean(x[: len(x) // hop * hop].reshape(-1, hop) ** 2, 1)) + 1e-9)
lv, lm = lev(v), lev(mb)
ctx = maximum_filter1d(median_filter(lv, 21), 21)          # surrounding phrase level (~400 ms)
phrase = ctx > lv.max() - 30                               # inside a sung phrase
dip = (ctx - lv > DROP) & phrase
events, i = [], 0
while i < len(dip):
    if dip[i]:
        j = i
        while j < len(dip) and dip[j]: j += 1
        dur = (j - i) * 0.02
        if 0.04 <= dur <= 0.6 and j < len(lv) and lv[min(j + 5, len(lv) - 1)] > ctx[j] - 4:  # recovers
            a, b = max(i - 10, 0), min(j + 10, len(lm))
            depth_v = ctx[i:j].mean() - lv[i:j].mean()
            depth_m = np.median(lm[a:b]) - lm[i:j].mean()
            events.append((i * 0.02, dur, depth_v, depth_m))
        i = j
    else:
        i += 1
gen = [e for e in events if e[3] > e[2] * 0.5]
sep = [e for e in events if e[3] <= e[2] * 0.5]
print(f"{len(events)} dips >= {DROP} dB  | also in mix (generated): {len(gen)}  | stem only (separator): {len(sep)}")
for t, d, dv, dm in events:
    print(f"  {int(t // 60)}:{t % 60:05.2f}  {d * 1000:4.0f} ms  stem -{dv:4.1f} dB  mix -{dm:4.1f} dB  -> {'GENERATED' if dm > dv * 0.5 else 'SEPARATOR'}")
